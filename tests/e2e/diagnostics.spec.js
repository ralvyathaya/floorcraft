import { expect, test } from '@playwright/test';
import { caseStudy } from '../../src/app/caseStudy.js';
import { cafePresets, legacyPresets } from '../../src/app/presets.js';
import { createRun, step, finish } from '../../src/simulation/engine.js';
import { createScenario } from '../../src/simulation/scenario.js';
import { deriveDiagnostics } from '../../src/simulation/diagnostics.js';

function result(layout, runNumber = 1) {
  const run = createRun(layout, createScenario(layout)); while (!run.done) step(run);
  return { ...finish(run), runNumber };
}
const saved = page => page.evaluate(() => JSON.parse(localStorage.getItem('floorcraft.workspace.v1')));
async function seed(page, workingLayout, baseline, latest = baseline) {
  await page.evaluate(doc => localStorage.setItem('floorcraft.workspace.v1', JSON.stringify(doc)), { schemaVersion: 1, workingLayout, baseline, latest });
  await page.reload();
}
test.beforeEach(async ({ page }) => {
  await page.goto('/'); await page.evaluate(() => localStorage.clear()); await page.reload();
  await expect(page.locator('.canvas-shell')).toHaveAttribute('data-assets', 'ready');
});

test('case start cancel/confirm, Undo and run locks protect the existing workspace', async ({ page }) => {
  const original = result(cafePresets[0].layout);
  await seed(page, original.layout, original);
  await page.getByText('12-seat case study', { exact: true }).click();
  await expect(page.getByRole('button', { name: 'Apply B', exact: true })).toBeDisabled();
  const before = await saved(page);
  await page.getByRole('button', { name: 'Start example', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('cleared comparison results cannot be restored with Undo');
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  expect(await saved(page)).toEqual(before);
  await expect(page.getByRole('button', { name: 'Start example', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Start example', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Start example', exact: true }).click();
  expect((await saved(page)).baseline).toBeNull(); expect((await saved(page)).workingLayout).toEqual(caseStudy.layouts.a);
  await page.getByRole('button', { name: 'Undo', exact: true }).click();
  expect((await saved(page)).workingLayout).toEqual(original.layout);
  await page.getByRole('button', { name: 'Start example', exact: true }).click();
  await page.getByRole('button', { name: 'Simulate Rush Hour' }).click();
  await expect(page.getByRole('button', { name: 'Start example', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Apply B', exact: true })).toBeDisabled();
  await expect(page.getByLabel('Flow diagnostics')).toHaveCount(0);
  await page.getByRole('button', { name: 'Stop Simulation' }).click();
  expect((await saved(page)).latest).toBeNull();
});

test('live equal-capacity A/B runs compute the actual service versus obstruction trade-off', async ({ page }, info) => {
  test.setTimeout(150000);
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (['error', 'warning'].includes(m.type())) errors.push(m.text()); });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByText('12-seat case study', { exact: true }).click();
  await page.getByRole('button', { name: 'Start example', exact: true }).click();
  await page.getByRole('button', { name: '32×', exact: true }).click();
  await page.getByRole('button', { name: 'Simulate Rush Hour' }).click();
  await expect(page.getByText('Simulation complete', { exact: true })).toBeVisible({ timeout: 75000 });
  const a = (await saved(page)).baseline;
  expect(a.metrics).toMatchObject({ seatingCapacity: 12, completed: 24, dineInServed: 12, switchedToTakeaway: 6, baristaWalkingMeters: 240 });
  await page.getByRole('button', { name: 'Apply B', exact: true }).click();
  expect((await saved(page)).baseline).toEqual(a); expect((await saved(page)).latest).toEqual(a);
  await page.getByRole('button', { name: 'Simulate Rush Hour' }).click();
  await expect(page.getByText('Simulation complete', { exact: true })).toBeVisible({ timeout: 75000 });
  const b = (await saved(page)).latest;
  expect(b.metrics).toMatchObject({ seatingCapacity: 12, completed: 24, dineInServed: 12, switchedToTakeaway: 6, baristaWalkingMeters: 96 });
  expect(b.metrics.averageOrderToReadySeconds).toBeLessThan(a.metrics.averageOrderToReadySeconds);
  expect(b.metrics.congestionPercent).toBeGreaterThan(a.metrics.congestionPercent);
  const takeaway = page.getByLabel('Experiment takeaway');
  await expect(takeaway).toContainText('Same capacity · 12 seats');
  await expect(takeaway).toContainText('Order → ready fell 63.4s; movement obstruction rose 1.2pp');
  await page.getByLabel('Flow diagnostics').scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath('ab-diagnostics-desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.getByRole('button', { name: 'Show on tested layout: Area 1', exact: true }).click();
  await expect(page.locator('.canvas-shell')).toHaveAttribute('data-editable', 'false');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const button = await page.getByRole('button', { name: 'Show on tested layout: Area 1', exact: true }).boundingBox(); expect(button.height).toBeGreaterThanOrEqual(44);
  await page.screenshot({ path: info.outputPath('ab-hotspot-narrow.png'), fullPage: true });
  await page.reload(); expect((await saved(page)).baseline).toEqual(a); expect((await saved(page)).latest).toEqual(b);
  await expect(page.getByLabel('Flow diagnostics')).toContainText('Run 2 · Latest');
  await page.getByRole('button', { name: 'Simulate Rush Hour' }).click();
  await expect(page.getByLabel('Flow diagnostics')).toHaveCount(0);
  await page.getByRole('button', { name: 'Stop Simulation' }).click();
  expect((await saved(page)).latest).toEqual(b);
  await expect(page.getByLabel('Flow diagnostics')).toContainText('Run 2 · Latest');
  expect(errors).toEqual([]);
});


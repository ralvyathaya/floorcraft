test('different-capacity context and legacy unavailable diagnostics survive reload and preview', async ({ page }) => {
  const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (['error', 'warning'].includes(m.type())) errors.push(m.text()); });
  const a = result(cafePresets[0].layout); const b = result(cafePresets[2].layout, 2);
  await seed(page, b.layout, a, b);
  await expect(page.getByLabel('Experiment takeaway')).toContainText('Different capacity · 8 → 16 seats');
  await expect(page.getByLabel('Experiment takeaway')).toContainText('Capacity and layout both changed');
  const old = result(legacyPresets[0].layout);
  await seed(page, b.layout, old, b);
  await page.getByRole('button', { name: 'Baseline Preview', exact: true }).click();
  const diagnostics = page.getByLabel('Flow diagnostics');
  await expect(diagnostics).toContainText('Unavailable');
  await page.getByText('12-seat case study', { exact: true }).click();
  await expect(page.getByRole('button', { name: 'Start example', exact: true })).toBeDisabled();
  expect((await saved(page)).baseline).toEqual(old);
  await seed(page, b.layout, old, { ...b, engineVersion: 'unknown' });
  await expect(page.getByText(/baseline retained/, { exact: false })).toBeVisible();
  await page.getByRole('button', { name: 'Baseline Preview', exact: true }).click();
  await expect(page.getByLabel('Flow diagnostics')).toContainText('Run 1 · Baseline');
  expect((await saved(page)).baseline).toEqual(old); expect((await saved(page)).latest).toBeNull();
  await seed(page, b.layout, { ...old, engineVersion: 'unknown' }, b);
  await expect(page.getByText(/its baseline is unavailable/)).toBeVisible();
  const reset = page.getByRole('button', { name: 'Start New Comparison', exact: true });
  await expect(reset).toBeEnabled();
  await reset.click();
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  expect((await saved(page)).latest).toEqual(b);
  await reset.click();
  await page.getByRole('button', { name: 'Clear comparison', exact: true }).click();
  expect((await saved(page)).latest).toBeNull();
  expect((await saved(page)).workingLayout).toEqual(b.layout);
  expect(errors).toEqual([]);
});
